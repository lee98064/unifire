import { z } from 'zod'
import { Id, Mac, Ts } from './common'

export const MatchingTarget = z.enum(['INTERNET', 'DOMAIN', 'IP', 'REGION'])

/** Route source, mirrors UniFi `target_devices[]`. */
export const RouteTarget = z.discriminatedUnion('type', [
  z.object({ type: z.literal('CLIENT'), mac: Mac }),
  z.object({ type: z.literal('NETWORK'), networkId: Id }),
  z.object({ type: z.literal('ALL_CLIENTS') }),
])

/**
 * Why Unifire may or may not write a UniFi route.
 * - managed: owned/adopted by Unifire (writable)
 * - probe: Unifire's own [unifire-probe] routes
 * - external: plain UniFi route, adoptable
 * - excluded: on the user's never-touch list
 * - object: generated by an Object (origin_type=object_pbr) — read-only
 * - predefined: UniFi predefined — read-only
 */
export const RouteOwnership = z.enum(['managed', 'probe', 'external', 'excluded', 'object', 'predefined'])

/** Route source as listed from UniFi — includes types Unifire doesn't model (kept read-only). */
export const UnifiRouteTarget = z.union([RouteTarget, z.object({ type: z.literal('OTHER'), raw: z.string() })])

/** Every UniFi traffic route, as listed by GET /api/routes (never omit routes; unknown shapes are read-only). */
export const UnifiRoute = z.object({
  id: Id, // UniFi _id
  description: z.string(),
  enabled: z.boolean(),
  /** INTERNET | DOMAIN | IP | REGION, or an unfamiliar value from newer firmware. */
  matchingTarget: z.string(),
  targets: z.array(UnifiRouteTarget),
  /** Destination summary for DOMAIN / IP / REGION routes (human readable, e.g. ["example.com", "1.2.3.0/24", "US"]). */
  destinations: z.array(z.string()),
  /** Top-level network_id; null for next-hop-only routes. */
  egressId: Id.nullable(),
  /** Next-hop IP for next-hop routes, else null. */
  nextHop: z.string().nullable(),
  killSwitch: z.boolean(),
  ownership: RouteOwnership,
  managedRouteId: Id.nullable(),
  /** Audit detected periodic external modifications (likely another automation). */
  suspectedAutomation: z.boolean(),
  lastExternalChangeAt: Ts.nullable(),
})

/** 7×24 grid: grid[day][hour] = egress id, or null = use defaultEgressId. day 0 = Monday. */
export const ScheduleGrid = z.array(z.array(Id.nullable()).length(24)).length(7)

/** Optional generator metadata so the UI can re-open the rotation generator with the same settings. */
export const RotationGenerator = z.object({
  /** Hours pinned to a specific egress, applied to every selected day. */
  pinned: z.array(z.object({ hour: z.number().int().min(0).max(23), egressId: Id })),
  /** Egresses cycled through the remaining hours in order. */
  cycle: z.array(Id).min(1),
  /** Cycle restarts every day at the first non-pinned hour or continues across days. */
  continuity: z.enum(['daily-reset', 'continuous']),
  days: z.array(z.number().int().min(0).max(6)),
})

export const RouteSchedule = z.object({
  timezone: z.string().default('Asia/Taipei'),
  grid: ScheduleGrid,
  generator: RotationGenerator.nullable().default(null),
})

export const FailoverPolicy = z.object({
  enabled: z.boolean(),
  /** Ordered fallbacks; the first healthy one is used when the desired egress is down. */
  chain: z.array(Id),
  /** Consecutive failed probe rounds before failing over. */
  failThreshold: z.number().int().min(1).max(20).default(3),
  /** Loss percentage over the last window that counts as failed. */
  lossPct: z.number().min(1).max(100).default(50),
  /** Minutes the desired egress must be healthy before switching back. */
  recoverMinutes: z.number().int().min(1).max(240).default(5),
})

export const SwitchReason = z.enum(['schedule', 'default', 'override', 'failover', 'recover', 'manual', 'rule', 'initial'])

export const ManagedRouteState = z.enum(['active', 'paused', 'drift', 'error', 'pending'])

export const RouteOverride = z.object({
  id: Id,
  managedRouteId: Id,
  egressId: Id,
  startsAt: Ts,
  endsAt: Ts,
  reason: z.string().nullable(),
  createdBy: z.string(), // "user:<id>" | "rule:<id>"
})

export const ManagedRoute = z.object({
  id: Id,
  unifiRouteId: Id,
  name: z.string(),
  /** Whether Unifire actively reconciles this route. */
  enabled: z.boolean(),
  state: ManagedRouteState,
  stateDetail: z.string().nullable(),
  matchingTarget: MatchingTarget,
  targets: z.array(RouteTarget),
  destinations: z.array(z.string()),
  killSwitch: z.boolean(),
  defaultEgressId: Id,
  schedule: RouteSchedule.nullable(),
  failover: FailoverPolicy,
  /** What UniFi currently has. */
  actualEgressId: Id.nullable(),
  /** What Unifire wants right now and why. */
  desired: z.object({ egressId: Id, reason: SwitchReason, until: Ts.nullable() }),
  activeOverride: RouteOverride.nullable(),
  next: z.object({ at: Ts, egressId: Id, reason: SwitchReason }).nullable(),
  lastSwitchAt: Ts.nullable(),
  createdAt: Ts,
})

/** POST /api/managed-routes — adopt an existing UniFi route or create a new one. */
export const ManagedRouteCreateInput = z.discriminatedUnion('mode', [
  z.object({
    mode: z.literal('adopt'),
    unifiRouteId: Id,
    name: z.string().min(1).max(80).optional(),
    defaultEgressId: Id.optional(),
    /** Required when audit flags the route as changed by outside automation: the admin confirms it was stopped. */
    acknowledgeAutomation: z.boolean().default(false),
  }),
  z.object({
    mode: z.literal('create'),
    name: z.string().min(1).max(80),
    targets: z.array(RouteTarget).min(1),
    matchingTarget: MatchingTarget.default('INTERNET'),
    /** For DOMAIN/IP/REGION: raw entries (domains, IP/CIDR, ISO country codes). */
    destinations: z.array(z.string()).default([]),
    killSwitch: z.boolean().default(true),
    defaultEgressId: Id,
  }),
])

export const ManagedRouteUpdateInput = z.object({
  name: z.string().min(1).max(80).optional(),
  enabled: z.boolean().optional(),
  defaultEgressId: Id.optional(),
  killSwitch: z.boolean().optional(),
  failover: FailoverPolicy.partial().optional(),
})

/** PUT /api/managed-routes/:id/schedule (null clears the schedule). */
export const ScheduleInput = RouteSchedule.nullable()

/** POST /api/managed-routes/:id/override */
export const OverrideInput = z.object({
  egressId: Id,
  /** Duration in minutes from now, or explicit end. */
  minutes: z.number().int().min(1).max(60 * 24 * 14).optional(),
  endsAt: Ts.optional(),
  reason: z.string().max(200).optional(),
}).refine(v => v.minutes != null || v.endsAt != null, { message: 'minutes or endsAt required' })

/** GET /api/managed-routes/:id/preview?hours=48 */
export const RoutePreview = z.object({
  managedRouteId: Id,
  segments: z.array(z.object({ start: Ts, end: Ts, egressId: Id, reason: SwitchReason })),
})

export const SwitchLogEntry = z.object({
  id: Id,
  ts: Ts,
  managedRouteId: Id,
  routeName: z.string(),
  fromEgressId: Id.nullable(),
  toEgressId: Id,
  reason: SwitchReason,
  /** Read-back after PUT matched. */
  verified: z.boolean(),
  dryRun: z.boolean(),
  durationMs: z.number().nullable(),
  error: z.string().nullable(),
})

export type MatchingTargetT = z.infer<typeof MatchingTarget>
export type RouteTargetT = z.infer<typeof RouteTarget>
export type RouteOwnershipT = z.infer<typeof RouteOwnership>
export type UnifiRouteT = z.infer<typeof UnifiRoute>
export type UnifiRouteTargetT = z.infer<typeof UnifiRouteTarget>
export type ScheduleGridT = z.infer<typeof ScheduleGrid>
export type RotationGeneratorT = z.infer<typeof RotationGenerator>
export type RouteScheduleT = z.infer<typeof RouteSchedule>
export type FailoverPolicyT = z.infer<typeof FailoverPolicy>
export type SwitchReasonT = z.infer<typeof SwitchReason>
export type ManagedRouteT = z.infer<typeof ManagedRoute>
export type ManagedRouteStateT = z.infer<typeof ManagedRouteState>
export type RouteOverrideT = z.infer<typeof RouteOverride>
export type ManagedRouteCreateInputT = z.infer<typeof ManagedRouteCreateInput>
export type RoutePreviewT = z.infer<typeof RoutePreview>
export type SwitchLogEntryT = z.infer<typeof SwitchLogEntry>
